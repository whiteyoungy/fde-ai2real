def srcline(s, kind, src, y=6.62):
    """页脚出处。档位配色与 deck_kit.maxim 共用一套，别在这里另立。"""
    tf = tb(s, ML, y, CW, 0.4)
    rich(tf, [(kind, {'color': MAXIM_KIND[kind], 'bold': True, 'size': 11}),
              ("\u3000\u3000", {}), (src, {'color': MUTED, 'size': 11.5})],
         size=11.5, color=MUTED, first=True, spacing=1.3)


def qpage(num, text, expand, kind, src, qsize=34, panel=False):
    s = D.slide(PANEL if panel else GROUND)
    eyebrow(s, num, "FDE 十二条", DECK)
    maxim(s, text, expand, kind, src, size=qsize)
    return s


