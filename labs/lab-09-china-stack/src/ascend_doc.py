def cpu_section(record: dict | None) -> str:
    """文末的实测章节。

    这一节是整份文档里唯一可以给数字的地方，因为它背后有真实运行记录。
    这里**绝不能出现「未实测」「未验证」字样**——它是实测跑通的，标成
    未实测就是标注滥用（verify.sh 第 7 项的对偶检查查的就是这个）。

    读不到实测记录时，如实说明记录缺失、给出补齐命令，同样不编数字。
    """
    head = [
        "",
        "---",
        "",
        "## 附录 · CPU 路径（本 Lab 已实测跑通，与上文状态不同）",
        "",
        "本节与上文性质不同：这里的每一个数字都来自本机真实运行，"
        "由 `python3 -m src.deploy_cpu` 产出，可复现。",
        "上文昇腾部分的标注不适用于本节，请勿混读。",
        "",
    ]
    if not record:
        head += [
            "> 本次生成文档时没有读到 `results/cpu_deploy.json`。",
            "> 先执行 `python3 -m src.deploy_cpu --backend http://127.0.0.1:11434`，",
            "> 再重新生成本文档，本节即会带上真实实测数字。",
            "> 这里不填任何占位数字——空着比填一个假的好。",
            "",
        ]
        return "\n".join(head)

    vram = record.get("vram_bytes")
    if vram is None:
        vram_line = ("推理期间的显存占用：`/api/ps` 未返回可用数据，"
                     "本次无法据此断言算力位置。")
    elif vram == 0:
        vram_line = ("推理期间的显存占用为 **0 字节**（后端 `/api/ps` 上报），"
                     "权重全部驻留内存——这是「确实走的是 CPU」的直接证据，"
                     "而不是推断。")
    else:
        vram_line = (f"推理期间的显存占用为 {vram / 1024 ** 3:.2f}GB，"
                     f"说明后端把权重卸载到了加速卡上，本条记录不能当作"
                     f"纯粹依靠处理器完成推理的证据。")

    body = [
        "### 实测记录",
        "",
        "| 项 | 值 |",
        "|---|---|",
        f"| 后端 | {record.get('backend')} {record.get('backend_version', '')} "
        f"@ `{record.get('backend_url')}` |",
        f"| 模型 | `{record.get('model')}` |",
        f"| 提示词 token 数 | {record.get('prompt_tokens')} |",
        f"| 生成 token 数 | {record.get('eval_tokens')} |",
        f"| 单次耗时 | {record.get('elapsed_s')} 秒 |",
        f"| 生成速率 | {record.get('tokens_per_s')} tok/s |",
        f"| 记录时间 | {record.get('measured_at')} |",
        "",
        vram_line,
        "",
        "### 这些数字能说明什么、不能说明什么",
        "",
        "**能说明**：在没有加速卡的机器上，把一个小参数量的国产开源模型",
        "拉起来并拿到正确的中文输出，这条链路是通的。演示环境、离线现场、",
        "客户的旧服务器上做可行性验证，这条路走得通。",
        "",
        "**不能说明**：0.5B 档位只用于验证部署链路，**不用于验证效果**。",
        "拿本节的回答质量去推断生产可用性是误用。同样，本节的耗时只反映",
        "这台机器、这个参数量、这个 token 数下的表现，换档位或换机器后",
        "全部作废，需要重新测。",
        "",
        "**为什么这一节可以给数字，而上文不行**：区别只有一个——这一节的",
        "数字有原始运行记录（`results/cpu_deploy.json`）撑着，上文没有。",
        "能验的就要验，验了就如实写验了；验不了的就标清楚验不了。",
        "两句话都说出来，读者才知道哪一句可以拿去做决策。",
        "",
    ]
    return "\n".join(head + body)


def render(record: dict | None) -> str:
    return HEADER + STATUS_TABLE + BODY + cpu_section(record)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="生成昇腾部署说明")
    ap.add_argument("--out", default="results")
    args = ap.parse_args(argv)

    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    record = None
    src = out / "cpu_deploy.json"
    if src.exists():
        try:
            record = json.loads(src.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as e:
            print(f"（读不到 CPU 实测记录，附录将说明记录缺失：{e}）")

    dest = out / "ascend_deploy.md"
    dest.write_text(render(record), encoding="utf-8")
    print(f"written={dest}（CPU 实测记录：{'已附' if record else '缺失'}）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
