"""脱敏中间件。

第 13 章原文：「脱敏后的日志才允许写入持久化存储或转发给 Langfuse——这一步顺序不能反。」

这个模块的定位不是「过滤器」，而是**信任边界上的闸门**：
凡是要离开本进程的文本（进 span 属性、进检索索引、发给模型厂商 API），
都必须先过一遍 `redact()`。原文只在 `app.py` 的函数局部变量里存在，
从不以原样形态跨出边界。

为什么是「进属性之前」而不是「上报之后」：
OTLP 的导出是批量异步的，一旦 span 属性被设上，原文就已经在
BatchSpanProcessor 的队列里了；此时再想「导出前统一清洗」，得去 hook
exporter，而 exporter 之外还有异常事件、span 名字等旁路。把闸门放在
写属性的那一行，是唯一能覆盖全部路径的位置。

—— 正则档的适用边界（README「可替换组件」已声明）——
结构化标识符（手机号 / 身份证 / 银行卡 / 邮箱）用正则是可靠的，因为它们
自带校验结构。姓名与地址靠词表 + 构词规则，**在真实语料上不够**：
换十个写法的地址就能绕过（README 延伸练习 1）。生产环境应当按第 13 章的
建议「正则打头阵、NER 兜底自由文本」。本 Lab 只做正则档。

—— 为什么不能图省事全掩 ——
verify.sh 第 5 项是第 4 项的对偶：`must_keep` 里的单据号、工单号、金额、
日期必须仍然可见。一份把订单号也打成 `****` 的 trace，排障时等于没有。
所以下面每条正则都带了收紧条件：
  · 手机号带号段约束 `1[3-9]`，不是 `\\d{11}`——否则 11 位的单据流水号会被吃掉
  · 身份证带日期段结构校验，不是 `\\d{18}`
  · 银行卡带发卡行前缀 + 长度约束，不是 `\\d{6,}`——否则金额 128000 会被吃掉
  · 金额、日期、单据号一律不设规则：它们是业务字段，不是 PII
"""
from __future__ import annotations

import re
from typing import Any

# ── 结构化标识符 ────────────────────────────────────────────────

# 邮箱。
_EMAIL = re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}")

# 身份证（18 位）。必须带日期段结构，否则任意 18 位数字都会被误伤。
# 结构：6 位地区码 + 4 位年（18/19/20 开头）+ 2 位月 + 2 位日 + 3 位顺序码 + 1 位校验位。
_ID_CARD = re.compile(
    r"(?<![0-9Xx])"
    r"[1-9]\d{5}"                       # 地区码
    r"(?:18|19|20)\d{2}"                # 年
    r"(?:0[1-9]|1[0-2])"                # 月
    r"(?:0[1-9]|[12]\d|3[01])"          # 日
    r"\d{3}[\dXx]"                      # 顺序码 + 校验位
    r"(?![0-9Xx])"
)

# 银行卡。带发卡行前缀与标准长度（16/19 位），不是笼统的 `\d{6,}`。
# 只写常见前缀：62 银联、4 Visa、5[1-5] MasterCard。
_BANK_CARD = re.compile(
    r"(?<!\d)(?:62\d{14}|62\d{17}|4\d{15}|4\d{18}|5[1-5]\d{14})(?!\d)"
)

# 中国大陆手机号。`1[3-9]` 的号段约束是关键：
# 用 `\d{11}` 的话，11 位的单据流水号、订单号都会被一起掩掉。
_PHONE = re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)")

# ── 住址 ────────────────────────────────────────────────────────
# 以「街道单元 + 门牌号」为锚（xx路 nn号 n单元 nnn室），前面留一个 1–8 字的
# 窗口把紧邻的行政区划一并带上（「北京市朝阳区建国路 88 号」整段掩掉）。
#
# 不要试图把行政区划写成独立的可选前缀。`(?:[一-龥]{2,4}市)?` 这种写法会从
# 句子中间任意位置起匹配——「王五住在北京市…」里的「住在北」+「京市」同样
# 满足它，结果把「住在」一起吃掉。锚定门牌号、前缀只给定长窗口，
# 匹配的左边界才是确定的。
#
# 反过来，锚点必须是门牌号而不是「路 / 街」本身：只匹配「xx路」的话，
# 「建国路支行」「中山路营业厅」这类机构名会被误伤，而它们是业务信息。
_ADDRESS = re.compile(
    r"[一-龥]{1,8}(?:路|街|道|巷|里|村|大厦|小区|花园)"
    r"\s*\d{1,4}\s*号"
    r"(?:\s*\d{1,4}\s*(?:号楼|栋|幢|单元|层))*"
    r"(?:\s*\d{1,5}\s*室)?"
)

# ── 姓名（词表档）────────────────────────────────────────────────
# README 已声明这一档「在真实语料上不够」。这里用「百家姓词表 + 名字长度 +
# 停用词表」三重约束，目的是在不误伤业务字段的前提下拦住常见写法。
_SURNAMES = (
    "王李张刘陈杨黄赵吴周徐孙马朱胡郭何林罗郑梁谢宋唐许韩冯邓曹彭曾萧田董潘"
    "袁蒋蔡余杜叶程苏魏吕丁任沈姚卢姜崔钟谭陆汪范金石廖贾夏韦付方白邹孟熊秦"
    "邱江尹薛闫段雷侯龙史陶黎贺顾毛郝龚邵万钱严覃武戴莫孔向汤"
)

# 不可能出现在名字末字的虚词 / 功能字。命中就从右往左削，
# 「王五住在…」削掉「住」还原成「王五」，而不是把「住」也当成名字的一部分。
_NON_GIVEN = set(
    "住在的了是和与有到说请把被给来去要能会可就都也还又再从对向为于"
    "号单据额信息里已及或由等该其此这那个们上下中内外前后时分元年月日"
    "件成本用做作让使得很太最更再多少大小新旧好坏"
)

# 停用词表：姓氏字同时是常用词首字的情况（金额、余额、周期…）。
# 这类误伤最致命——「金额 4500」被掩成「[NAME] 4500」还算轻，真实语料里
# 「任务」「严重」「顾客」「余额」被当成人名，会让整份日志不可读。
# 词条偏企业运维语料，因为这是本 Lab 的目标场景；换个领域要换这张表——
# 这也正是 README 说正则档「在真实语料上不够」的地方。
_COMMON_WORDS = {
    # 财务 / 单据
    "金额", "金融", "余额", "余下", "余量", "成本", "付款", "付费", "付出",
    "万一", "万元", "钱包", "钱款", "预付",
    # 时间
    "周一", "周二", "周三", "周四", "周五", "周六", "周日", "周末", "周期",
    "夏天", "夏季", "史上", "曾经",
    # 流程 / 状态
    "方式", "方案", "方法", "方向", "方面", "方便", "任务", "任何", "任意",
    "严重", "严格", "严肃", "程序", "程度", "范围", "范例", "段落", "向上",
    "向下", "向前", "向后", "向导", "许可", "许多", "高级", "高效", "高度",
    "高于", "马上", "马虎", "顾客", "顾问", "董事", "章节", "章程",
    # 其它高频词
    "白天", "白色", "黄色", "黄金", "石头", "石油", "江苏", "江湖", "何时",
    "何况", "何必", "毛病", "毛巾", "龙头", "武汉", "武器", "孔子", "孟子",
    "秦朝", "雷同", "雷达", "温度", "黎明", "陶瓷", "贺卡", "莫非", "莫名",
    "田地", "田野", "叶子", "苏州", "沈阳", "陆续", "陆地", "谢谢", "郑重",
    "罗列", "林业", "胡乱", "胡说", "张贴", "张开", "戴上", "汤圆", "孔洞",
}

# 姓氏字紧跟在数量词 / 指示词后面时，几乎一定不是姓。
# 「入职日期前一周收齐」里的「周」就是这样被误当成姓的（周 是常见姓氏），
# 结果掩成「前一[NAME]」。左侧上下文一票否决，比往停用词表里塞
# 「周收齐」这种临时组合可靠得多。
_NOT_SURNAME_AFTER = "一二三四五六七八九十两半本每该上下前后这那几多整整数第"

# 名字右边界。姓名后面常直接跟称谓或动词，正则的 `{1,2}` 会贪心吃进去：
# 「张伟经理」被吃成「张伟经」，掩完剩一个孤零零的「理」。
# 判断依据是「当前末字与后一个字能否成词」——能成词，说明这个字属于后面那个词。
_RIGHT_WORDS = {
    "经理", "先生", "女士", "主管", "老师", "医生", "同学", "部长", "总监",
    "总裁", "董事", "顾问", "工程", "团队", "部门", "中心", "客户", "同事",
    "收齐", "统一", "负责", "确认", "反馈", "提交", "审核", "处理", "完成",
    "说明", "表示", "认为", "建议", "要求", "需要", "已经", "正在", "报销",
}

_NAME = re.compile(rf"(?<![{_NOT_SURNAME_AFTER}])[{_SURNAMES}][一-龥]{{1,2}}")

# 各类占位符。用方括号包起来，人眼一看就知道「这里被掩过」，
# 而不是 `****`——后者分不清是脱敏了还是数据本来就缺失。
MASK_EMAIL = "[EMAIL]"
MASK_ID = "[ID_CARD]"
MASK_BANK = "[BANK_CARD]"
MASK_PHONE = "[PHONE]"
MASK_ADDRESS = "[ADDRESS]"
MASK_NAME = "[NAME]"


def _name_sub(m: re.Match) -> str:
    """姓名替换。先从右往左削虚词，再过停用词表，最后才判定为人名。"""
    matched = m.group(0)

    # 姓 + 首字已经构成常用词，整段就不是人名。
    # 必须查**前两字**而不是整段：「次周二统一打款」正则会吃到「周二统」，
    # 查整段的话「周二统」不在词表里，就被当成人名掩掉了，
    # 结果「次周二」变成「次[NAME]一」——这类误伤在长文本里到处都是。
    if matched[:2] in _COMMON_WORDS:
        return matched

    name = matched
    while len(name) > 2 and name[-1] in _NON_GIVEN:
        name = name[:-1]

    # 末字与紧随其后的字成词 → 这个字属于后面那个词，不是名字的一部分。
    # 「张伟经」+「理」：经理成词，缩回「张伟」，掩成「[NAME]经理」。
    tail = m.string[m.end():m.end() + 1]
    while len(name) > 2 and (name[-1] + tail) in _RIGHT_WORDS:
        tail = name[-1]
        name = name[:-1]
    # 削到只剩「姓 + 一个虚词」，说明这根本不是人名（例：「向上」「到账」）
    if len(name) == 2 and name[-1] in _NON_GIVEN:
        return matched
    if name in _COMMON_WORDS:
        return matched
    # 只替换判定为人名的那一段，被削掉的尾巴原样留回去
    return MASK_NAME + matched[len(name):]


def redact_text(text: str) -> str:
    """对单段文本脱敏。

    顺序有讲究：先掩「长且结构强」的（身份证 18 位、银行卡 16/19 位），
    再掩短的（手机号 11 位）。所有数字类正则都带了 `(?<!\\d)`/`(?!\\d)`
    边界，所以顺序其实不会造成互相啃食——但保持长→短的顺序，
    换掉某条正则时不容易踩坑。
    """
    if not text:
        return text
    text = _EMAIL.sub(MASK_EMAIL, text)
    text = _ID_CARD.sub(MASK_ID, text)
    text = _BANK_CARD.sub(MASK_BANK, text)
    text = _PHONE.sub(MASK_PHONE, text)
    text = _ADDRESS.sub(MASK_ADDRESS, text)
    text = _NAME.sub(_name_sub, text)
    return text


def redact(obj: Any) -> Any:
    """递归脱敏任意可序列化对象。

    这是给闸门用的入口：调用方不需要知道自己手里是 str、dict 还是嵌套
    list——**只要是要跨出边界的东西，整个丢进来**。少写一处 `redact_text`
    就是一次泄漏，所以宁可无脑全过。

    dict 的 key 也要脱敏：把手机号当 key 的 metadata 是真实存在的写法。
    int/float/bool/None 原样返回（token 数、成本这类数值不需要脱敏，
    过一遍也不会被改坏）。
    """
    if obj is None or isinstance(obj, (bool, int, float)):
        return obj
    if isinstance(obj, str):
        return redact_text(obj)
    if isinstance(obj, dict):
        return {redact(k): redact(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [redact(x) for x in obj]
    if isinstance(obj, set):
        return [redact(x) for x in obj]
    # 兜底：不认识的类型先转字符串再脱敏。
    # 宁可把对象打成字符串，也不能让它带着原文原样进 span——
    # 异常对象就是走这条路进来的。
    return redact_text(str(obj))


if __name__ == "__main__":  # 手工试跑：python3 -m src.redact
    import json
    import pathlib
    import sys

    cases = pathlib.Path(__file__).resolve().parent.parent / "fixtures" / "pii_cases.jsonl"
    bad = 0
    for line in cases.open(encoding="utf-8"):
        c = json.loads(line)
        out = redact_text(c["text"])
        leaked = [v for v in c["must_mask"] if v in out]
        lost = [v for v in c["must_keep"] if v not in out]
        flag = "OK  " if not leaked and not lost else "FAIL"
        if leaked or lost:
            bad += 1
        print(f"[{flag}] {c['id']}  {out}")
        if leaked:
            print(f"        泄漏: {leaked}")
        if lost:
            print(f"        误伤: {lost}")
    print(f"\n{len(list(cases.open(encoding='utf-8')))} 条用例，{bad} 条不合格")
    sys.exit(1 if bad else 0)
