# 唯一的区分信号就是那串编号，而编号在长句里被大量常见词稀释掉了。
# 企业知识库里这类文档（工单、复盘报告、巡检记录、规格书）往往占大头。
INC_TOPICS = ["支付超时", "库存同步失败", "登录异常", "报表导出慢",
              "消息积压", "对账差异", "权限丢失", "接口限流"]
N_INCIDENT = 1200
for i in range(N_INCIDENT):
    code = f"INC-{20000 + i}"
    doc(f"d-{code.lower()}", f"{code} 生产事件复盘报告",
        f"事件现象为{INC_TOPICS[i % len(INC_TOPICS)]}，影响范围为部分用户，"
        "已于当日恢复。复盘结论：根因定位耗时偏长，监控告警存在延迟。"
        "改进项包括补充链路埋点、调整告警阈值、完善值班交接记录。"
        "本报告由事件指挥官归档，相关整改项纳入季度跟踪。"
        "附：时间线、影响评估、沟通记录、后续验证计划。", "复盘")

# 查询形态刻意做成「一段自然语言里埋着一个编号」——这是真实用户的问法，
# 也是最能把稠密检索拖垮的问法：编号只占整句的一小部分，语义信号全是噪声，
# 因为 1200 篇复盘报告的语义彼此几乎完全一样。
for j, i in enumerate(sorted(random.sample(range(N_INCIDENT), 40)), 1):
    code = f"INC-{20000 + i}"
    query(f"q-inc-{j:02d}",
          f"上次那个{INC_TOPICS[i % len(INC_TOPICS)]}的事件，编号好像是 {code}，"
          "复盘报告里改进项有哪些",
          [f"d-{code.lower()}"], "buried_id",
          "同质文档海中埋编号：语义信号全是噪声，只有精确词面能定位")

